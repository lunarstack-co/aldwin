def test_wheel_and_sdist_include_assets_and_exclude_dev_files(
    built_distributions: tuple[Path, Path],
) -> None:
    """TC-02: Wheel and sdist contain `aldwin/core/assets/*` and no dev/test files."""
    wheel_path, sdist_path = built_distributions

    with zipfile.ZipFile(wheel_path) as zf:
        wheel_names = set(zf.namelist())

    for asset in EXPECTED_WHEEL_ASSETS:
        assert asset in wheel_names, f"Missing {asset} in wheel"

    for entry in wheel_names:
        for forbidden in FORBIDDEN_ARCHIVE_PREFIXES:
            assert not entry.startswith(forbidden), (
                f"Forbidden path {entry!r} leaked into wheel"
            )
        assert "/tests/" not in entry

    with tarfile.open(sdist_path, "r:gz") as tf:
        sdist_names = set(tf.getnames())

    for asset in EXPECTED_WHEEL_ASSETS:
        expected_sdist_entry = f"aldwin-0.0.2.1/src/{asset}"
        assert expected_sdist_entry in sdist_names, (
            f"Missing {expected_sdist_entry} in sdist"
        )

    for required_root_file in (
        "README.md",
        "LICENSE",
        "CHANGELOG.md",
        "pyproject.toml",
    ):
        assert f"aldwin-0.0.2.1/{required_root_file}" in sdist_names

    for entry in sdist_names:
        rel_entry = entry.removeprefix("aldwin-0.0.2.1/")
        for forbidden in FORBIDDEN_ARCHIVE_PREFIXES:
            assert not rel_entry.startswith(forbidden), (
                f"Forbidden path {entry!r} leaked into sdist"
            )


def test_wheel_assets_loadable_from_unpacked_package(
    built_distributions: tuple[Path, Path],
    tmp_path: Path,
) -> None:
    """TC-15: Unpacked wheel contains valid starter assets and base instructions."""
    wheel_path, _ = built_distributions
    unpack_dir = tmp_path / "unpacked_wheel"
    with zipfile.ZipFile(wheel_path) as zf:
        zf.extractall(unpack_dir)

    assets_root = unpack_dir / "aldwin" / "core" / "assets"
    for asset_rel, _ in STARTER_ASSETS:
        asset_file = assets_root / asset_rel
        assert asset_file.is_file(), (
            f"Missing starter asset {asset_rel} in unpacked wheel"
        )
        assert asset_file.read_text(encoding="utf-8").strip() != ""

    instructions_text = (assets_root / "instructions.md").read_text(encoding="utf-8")
    assert "Aldwin" in instructions_text

    config_data = yaml.safe_load(
        (assets_root / "config.yaml").read_text(encoding="utf-8")
    )
    assert isinstance(config_data, dict)
    assert config_data.get("model") == "gpt-4o"

    tmpl = (assets_root / "skills" / "using-aldwin" / "SKILL.md.tmpl").read_text(
        encoding="utf-8"
    )
    assert "name: using-aldwin" in tmpl
    assert "$version" in tmpl and "$model" in tmpl
    assert (assets_root / "skills" / "files" / "SKILL.md").is_file()


def test_readme_uses_absolute_https_image_urls_and_balanced_fences() -> None:
    """TC-05: README uses absolute https:// image URLs and balanced code fences."""
    readme = (REPO_ROOT / "README.md").read_text(encoding="utf-8")

    md_images = re.findall(r"!\[[^\]]*\]\(([^)]+)\)", readme)
    html_images = re.findall(r'<img[^>]+src=["\']([^"\']+)["\']', readme)
    all_images = [*md_images, *html_images]
    assert all_images, "Expected at least one demo GIF image in README.md"

    for url in all_images:
        assert url.startswith(
            "https://raw.githubusercontent.com/lunarstack-co/aldwin/"
        ), (
            f"Image URL {url!r} must be an absolute raw.githubusercontent.com "
            "HTTPS URL so it renders on PyPI"
        )

    fence_lines = [
        line for line in readme.splitlines() if line.strip().startswith("```")
    ]
    assert len(fence_lines) % 2 == 0, "Unclosed ``` code fence in README.md"


