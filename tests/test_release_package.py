def test_wheel_and_sdist_include_assets_and_exclude_dev_files(
    built_distributions: tuple[Path, Path],
) -> None:
    """Wheel and sdist contain `aldwin/core/assets/*` and no dev/test files."""
    wheel_path, sdist_path = built_distributions

    with zipfile.ZipFile(wheel_path) as zf:
        wheel_names = set(zf.namelist())

    for asset in EXPECTED_WHEEL_ASSETS:
        assert asset in wheel_names, f"Missing {asset} in wheel"

    for entry in wheel_names:
        for forbidden in FORBIDDEN_ARCHIVE_PREFIXES:
            assert not entry.startswith(forbidden), (
                f"Forbidden path {entry!r} leaked into wheel"
            )
        assert "/tests/" not in entry

    with tarfile.open(sdist_path, "r:gz") as tf:
        sdist_names = set(tf.getnames())

    for asset in EXPECTED_WHEEL_ASSETS:
        expected_sdist_entry = f"aldwin-{VERSION}/src/{asset}"
        assert expected_sdist_entry in sdist_names, (
            f"Missing {expected_sdist_entry} in sdist"
        )

    for required_root_file in (
        "README.md",
        "LICENSE",
        "CHANGELOG.md",
        "pyproject.toml",
    ):
        assert f"aldwin-{VERSION}/{required_root_file}" in sdist_names

    for entry in sdist_names:
        rel_entry = entry.removeprefix(f"aldwin-{VERSION}/")
        for forbidden in FORBIDDEN_ARCHIVE_PREFIXES:
            assert not rel_entry.startswith(forbidden), (
                f"Forbidden path {entry!r} leaked into sdist"
            )


def test_wheel_ships_web_export_but_not_the_web_project(
    built_distributions: tuple[Path, Path],
) -> None:
    """The UI ships as static files only.

    The fixture builds without Node, so this also proves the committed page
    is enough for a Python-only build.
    """
    wheel_path, sdist_path = built_distributions
    with zipfile.ZipFile(wheel_path) as zf:
        web_entries = [n for n in zf.namelist() if n.startswith("aldwin/web/")]
        index_html = zf.read("aldwin/web/static/index.html").decode("utf-8")

    assert 'data-testid="aldwin-stub"' in index_html
    assert "aldwin/web/app.py" in web_entries
    assert "aldwin/web/routes/settings.py" in web_entries
    for entry in web_entries:
        name = entry.removeprefix("aldwin/web/")
        is_module = name.endswith(".py") and not name.startswith("static/")
        assert is_module or name.startswith("static/"), (
            f"Unexpected web file {entry!r} in wheel"
        )
        for marker in ("node_modules", "package.json", ".next/", "cypress"):
            assert marker not in entry, f"{entry!r} leaked into wheel"

    with tarfile.open(sdist_path, "r:gz") as tf:
        sdist_names = tf.getnames()
    assert any(n.startswith(f"aldwin-{VERSION}/") for n in sdist_names)
    assert not any(n.startswith(f"aldwin-{VERSION}/web/") for n in sdist_names)


