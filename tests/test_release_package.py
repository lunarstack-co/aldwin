@pytest.fixture(scope="module")
def built_distributions(tmp_path_factory: pytest.TempPathFactory) -> tuple[Path, Path]:
    """Build the wheel and sdist once into a temporary directory via `uv build`."""
    out_dir = tmp_path_factory.mktemp("dist")
    uv_bin = shutil.which("uv")
    assert uv_bin is not None, "Expected `uv` binary on PATH"

    proc = subprocess.run(
        [uv_bin, "build", "--out-dir", str(out_dir)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, f"uv build failed:\n{proc.stderr}\n{proc.stdout}"

    wheels = list(out_dir.glob("aldwin-*.whl"))
    sdists = list(out_dir.glob("aldwin-*.tar.gz"))
    assert len(wheels) == 1, f"Expected 1 wheel, found {wheels}"
    assert len(sdists) == 1, f"Expected 1 sdist, found {sdists}"
    return wheels[0], sdists[0]


@pytest.mark.uninitialized_home
def test_version_is_0_0_2_1(aldwin_home: Path) -> None:
    """TC-01: pyproject.toml, aldwin.__version__, and `aldwin --version` are 0.0.2.1."""
    pyproject_data = tomllib.loads(
        (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    )
    assert pyproject_data["project"]["version"] == "0.0.2.1"
    assert aldwin.__version__ == "0.0.2.1"
    expected = (
        f"aldwin 0.0.2.1 (protocol v2, agentling {metadata.version('agentling')})"
    )

    runner = CliRunner()
    res = runner.invoke(app, ["--version"])
    assert res.exit_code == 0
    assert res.output.strip() == expected
    assert not aldwin_home.exists()

    start = time.perf_counter()
    proc = subprocess.run(
        [sys.executable, "-m", "aldwin.cli.main", "--version"],
        capture_output=True,
        text=True,
        check=False,
    )
    elapsed = time.perf_counter() - start
    assert proc.returncode == 0
    assert proc.stdout.strip() == expected
    assert elapsed < 0.5
    assert not aldwin_home.exists()


def test_dependency_ranges_and_lock() -> None:
    """TC-03: every runtime dependency has a lower bound; the lock is in sync."""
    pyproject_data = tomllib.loads(
        (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    )
    deps = pyproject_data["project"]["dependencies"]
    assert "agentling>=0.1,<0.2" in deps
    assert any(d.startswith("packaging>=") for d in deps)
    for dep in deps:
        assert ">=" in dep, f"{dep!r} has no lower bound"

    uv_bin = shutil.which("uv")
    assert uv_bin is not None, "Expected `uv` binary on PATH"
    proc = subprocess.run(
        [uv_bin, "lock", "--check"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, f"uv lock --check failed:\n{proc.stderr}"


