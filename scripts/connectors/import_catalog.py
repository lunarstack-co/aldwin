"""Build the connector catalogue and app logos from the allowlist and the MCP Registry.

A maintainer tool, never shipped. Only vendors named in `allowlist.yaml` are used, and a
registry entry counts only when it is published under that vendor's own domain.

    uv run python scripts/connectors/import_catalog.py [--refresh] [--dry-run]
        [--offline] [--only NAME]

Exit codes: 0 every vendor made it in, 1 a vendor was left out (see the report),
2 the registry could not be reached.
"""

