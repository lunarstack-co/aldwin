_PLACEHOLDER = re.compile(r"\{[^}]*\}")


class Vendor(BaseModel):
    """One allowlisted app: the words people see, and where its server comes from."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: StrictStr
    title: StrictStr
    purpose: StrictStr
    keywords: list[str]
    category: Category
    docs_url: StrictStr
    logo: StrictStr
    source: Literal["registry", "manual"]
    namespace: StrictStr | None = None
    url: StrictStr | None = None
    remote: StrictStr | None = None
    expect_auth: AuthKind | None = None
    token_help_url: StrictStr | None = None
    oauth: OAuthSettings | None = None

    @field_validator("name")
    @classmethod
    def _name(cls, value: str) -> str:
        if not is_valid_name(value):
            raise ValueError(f"invalid connector name {value!r}")
        return value

    @field_validator("logo")
    @classmethod
    def _logo(cls, value: str) -> str:
        if not _LOGO.match(value):
            raise ValueError(
                "logo must be simple-icons:<slug>, lobehub:<id>, hand or letter"
            )
        return value

    @model_validator(mode="after")
    def _source_fields(self) -> Vendor:
        if self.source == "registry" and not self.namespace:
            raise ValueError("a registry vendor needs a namespace")
        if self.source == "manual" and not self.url:
            raise ValueError("a manual vendor needs a url")
        if self.expect_auth == "bearer" and not self.token_help_url:
            raise ValueError("a token app needs a token_help_url")
        return self


@dataclass(frozen=True)
class Rejection:
    """Why a vendor was left out, in words a maintainer can act on."""

    reason: str


class RegistryUnavailable(Exception):
    """The registry could not be read and there is no usable cache."""


def load_allowlist(path: Path = ALLOWLIST) -> list[Vendor]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    vendors = [Vendor.model_validate(item) for item in raw.get("vendors", [])]
    names = [v.name for v in vendors]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise ValueError(f"allowlist names repeat: {', '.join(duplicates)}")
    return vendors


# --- registry ------------------------------------------------------------------


def namespace_domain(namespace: str) -> str:
    """`com.stripe` -> `stripe.com`."""
    return ".".join(reversed(namespace.split(".")))


def is_shared_namespace(namespace: str) -> bool:
    if namespace.startswith(SHARED_NAMESPACE_PREFIXES):
        return True
    domain = namespace_domain(namespace)
    return any(domain == host or domain.endswith(f".{host}") for host in SHARED_HOSTS)


def _on_domain(url: str, domain: str) -> bool:
    host = (urlsplit(url).hostname or "").lower()
    return host == domain or host.endswith(f".{domain}")


def select_remote(servers: list[dict[str, Any]], vendor: Vendor) -> str | Rejection:
    """The vendor's current streamable HTTP address, or why there is none."""
    namespace = vendor.namespace or ""
    if is_shared_namespace(namespace):
        return Rejection("namespace is a shared host")
    current = [
        entry["server"]
        for entry in servers
        if str(entry.get("server", {}).get("name", "")).split("/")[0] == namespace
        and _official(entry).get("status") == "active"
        and _official(entry).get("isLatest") is True
    ]
    if not current:
        return Rejection(NO_REGISTRY_ENTRY)
    remotes = [
        str(remote.get("url", ""))
        for server in current
        for remote in server.get("remotes") or []
        if remote.get("type") == "streamable-http"
    ]
    if not remotes:
        return Rejection("no streamable HTTP address")
    filled = [url for url in remotes if not _PLACEHOLDER.search(url)]
    if not filled:
        return Rejection("address needs details")
    domain = namespace_domain(namespace)
    usable = [url for url in filled if _on_domain(url, domain)]
    if not usable:
        return Rejection("server isn't on the vendor's domain")
    if vendor.remote is not None:
        return (
            vendor.remote
            if vendor.remote in usable
            else Rejection("named remote isn't in the registry")
        )
    return usable[0]


def _official(entry: dict[str, Any]) -> dict[str, Any]:
    meta = entry.get("_meta") or {}
    official = meta.get("io.modelcontextprotocol.registry/official") or {}
    return official if isinstance(official, dict) else {}


async def fetch_registry(
    http: httpx2.AsyncClient,
    *,
    cache: Path = CACHE_DIR / "registry.json",
    refresh: bool = False,
) -> list[dict[str, Any]]:
    """Every current registry entry, from the cache unless `refresh` is set."""
    if cache.exists() and not refresh:
        loaded: list[dict[str, Any]] = json.loads(cache.read_text(encoding="utf-8"))
        return loaded
    entries: list[dict[str, Any]] = []
    cursor: str | None = None
    while True:
        params = {"limit": "100", "version": "latest"}
        if cursor:
            params["cursor"] = cursor
        page = await _get_json(http, REGISTRY_URL, params)
        entries.extend(page.get("servers") or [])
        cursor = (page.get("metadata") or {}).get("nextCursor")
        if not cursor:
            break
    cache.parent.mkdir(parents=True, exist_ok=True)
    temp = cache.with_suffix(".tmp")
    temp.write_text(json.dumps(entries), encoding="utf-8")
    temp.replace(cache)
    return entries


async def _get_json(
    http: httpx2.AsyncClient, url: str, params: dict[str, str]
) -> dict[str, Any]:
    for attempt in range(2):
        try:
            response = await http.get(url, params=params, timeout=REQUEST_TIMEOUT_S)
        except httpx2.HTTPError as exc:
            if attempt == 0:
                continue
            raise RegistryUnavailable(str(exc) or type(exc).__name__) from exc
        if response.status_code == 429 and attempt == 0:
            await asyncio.sleep(_retry_after(response))
            continue
        if response.is_success:
            body: dict[str, Any] = response.json()
            return body
        if attempt == 1 or response.status_code < 500:
            raise RegistryUnavailable(f"HTTP {response.status_code}")
    raise RegistryUnavailable("no answer")


def _retry_after(response: httpx2.Response) -> float:
    try:
        return min(30.0, max(0.0, float(response.headers.get("retry-after", "1"))))
    except ValueError:
        return 1.0


# --- sign-in ---------------------------------------------------------------------

_AUTH_WORDS: Final[dict[str, str]] = {
    "oauth": "browser sign-in",
    "bearer": "token sign-in",
    "none": "no sign-in",
}


async def classify_auth(
    vendor: Vendor, url: str, http: httpx2.AsyncClient
) -> AuthKind | Rejection:
    """How the server signs in, using the same checks Aldwin runs when connecting."""
    config = ConnectorConfig(
        name=vendor.name, url=url, auth="oauth", oauth=vendor.oauth
    )
    found: AuthKind
    try:
        discovery = await discover(config, client=http)
    except ConnectorUnreachable as exc:
        return Rejection(f"server didn't answer ({_unreachable_reason(exc)})")
    except SignInError as exc:
        if str(exc) != no_browser_sign_in(config.display_title, config.name):
            return Rejection(f"sign-in metadata is wrong: {exc}")
        found = "bearer"
    else:
        if discovery is None:
            found = "none"
        elif vendor.expect_auth == "bearer":
            # A token app may also advertise OAuth that Aldwin never uses, so its
            # registration options don't matter.
            found = "oauth"
        else:
            try:
                require_s256(vendor.title, discovery.asm)
            except SignInError:
                return Rejection("sign-in server doesn't support PKCE S256")
            try:
                choose_client_identity(
                    config, discovery.asm, DEFAULT_CLIENT_METADATA_URL
                )
            except SignInError:
                return Rejection("Aldwin can't register with this app")
            found = "oauth"
    return _reconcile(vendor, found)


def _reconcile(vendor: Vendor, found: AuthKind) -> AuthKind | Rejection:
    expected = vendor.expect_auth
    # A token app only has to refuse anonymous calls; it may also offer unused OAuth.
    if expected == "bearer" and found in ("bearer", "oauth"):
        return "bearer"
    if expected is not None and expected != found:
        return Rejection(
            f"expected {_AUTH_WORDS[expected]}, found {_AUTH_WORDS[found]}"
        )
    if found == "bearer" and not vendor.token_help_url:
        return Rejection("token sign-in needs a token_help_url in the allowlist")
    return found


def _unreachable_reason(exc: ConnectorUnreachable) -> str:
    message = str(exc).rstrip(".")
    return message.split(": ", 1)[1] if ": " in message else message


# --- logos -------------------------------------------------------------------------

_SVG_NS: Final = "{http://www.w3.org/2000/svg}"
_ALLOWED_TAGS: Final = {"svg", "g", "path", "title"}
_ALLOWED_ATTRS: Final = {
    "svg": {
        "viewBox",
        "xmlns",
        "fill",
        "fill-rule",
        "width",
        "height",
        "role",
        "style",
        "class",
    },
    "g": {"fill", "fill-rule"},
    "path": {"d", "fill", "fill-rule", "clip-rule", "opacity"},
    "title": set(),
}


@dataclass(frozen=True)
class MarkData:
    title: str
    view_box: str
    paths: list[dict[str, Any]] = field(default_factory=list)
    color: str | None = None
    fill_rule: str | None = None


def parse_svg(text: str, *, title: str, color: str | None) -> MarkData | None:
    """Path data from a simple SVG; `None` for anything beyond plain paths."""
    try:
        root = ET.fromstring(text)
    except ET.ParseError:
        return None
    if _tag(root) != "svg" or not root.get("viewBox"):
        return None
    paths: list[dict[str, Any]] = []
    for element in root.iter():
        tag = _tag(element)
        if tag not in _ALLOWED_TAGS:
            return None
        if any(_attr(name) not in _ALLOWED_ATTRS[tag] for name in element.attrib):
            return None
        if tag == "path":
            d = element.get("d")
            if not d:
                return None
            path: dict[str, Any] = {"d": d}
            if element.get("fill-rule") in ("evenodd", "nonzero"):
                path["fillRule"] = element.get("fill-rule")
            if element.get("opacity"):
                try:
                    path["opacity"] = float(element.get("opacity", "1"))
                except ValueError:
                    return None
            paths.append(path)
    if not paths:
        return None
    root_rule = root.get("fill-rule")
    return MarkData(
        title=title,
        view_box=root.get("viewBox", ""),
        paths=paths,
        color=color,
        fill_rule=root_rule if root_rule in ("evenodd", "nonzero") else None,
    )


def _tag(element: ET.Element) -> str:
    return element.tag.removeprefix(_SVG_NS)


def _attr(name: str) -> str:
    return name.rsplit("}", 1)[-1] if name.startswith("{") else name


def simple_icons_slug(title: str) -> str:
    """Simple Icons' slug rule: `+` plus, `.` dot, `&` and, then letters and digits."""
    text = title.replace("+", "plus").replace(".", "dot").replace("&", "and")
    text = unicodedata.normalize("NFD", text.lower())
    return "".join(ch for ch in text if ch.isascii() and ch.isalnum())


def usable_color(hex_color: str) -> str | None:
    """The brand colour, or `None` for near-black and near-white marks, which follow the
    text colour so they show in both themes.
    """
    value = hex_color.lstrip("#")
    if len(value) != 6:
        return None
    r, g, b = (int(value[i : i + 2], 16) / 255 for i in (0, 2, 4))
    luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b
    return f"#{value.upper()}" if 0.2 <= luminance <= 0.9 else None


def simple_icons_colors(data: list[dict[str, Any]]) -> dict[str, str]:
    return {
        str(
            icon.get("slug") or simple_icons_slug(str(icon.get("title", "")))
        ): f"#{icon['hex']}"
        for icon in data
        if icon.get("hex")
    }


async def fetch_mark(
    vendor: Vendor,
    http: httpx2.AsyncClient,
    colors: dict[str, str],
) -> MarkData | None:
    """The vendor's mark at the pinned icon versions; `None` means a letter mark."""
    source, _, slug = vendor.logo.partition(":")
    if source == "simple-icons":
        hex_color = colors.get(slug)
        url = f"{SIMPLE_ICONS}/icons/{slug}.svg"
        color = usable_color(hex_color) if hex_color else None
    elif source == "lobehub":
        url, color = f"{LOBEHUB}/icons/{slug}.svg", None
    else:
        return None
    try:
        response = await http.get(url, timeout=REQUEST_TIMEOUT_S)
    except httpx2.HTTPError:
        return None
    if not response.is_success:
        return None
    return parse_svg(response.text, title=vendor.title, color=color)


def hand_kept_marks(path: Path = MARKS_PATH) -> set[str]:
    """Names with a hand-kept mark, which always win over generated ones."""
    text = path.read_text(encoding="utf-8")
    return set(re.findall(r"^  ([a-z0-9]+): \{$", text, re.MULTILINE))


def render_app_marks(marks: dict[str, MarkData]) -> str:
    entries = []
    for name in sorted(marks):
        mark = marks[name]
        body: dict[str, Any] = {"title": mark.title}
        if mark.color:
            body["color"] = mark.color
        body["viewBox"] = mark.view_box
        if mark.fill_rule:
            body["fillRule"] = mark.fill_rule
        body["paths"] = mark.paths
        entries.append(f"  {name}: {json.dumps(body, ensure_ascii=False)},\n")
    return (
        APP_MARKS_HEADER
        + 'import type { Mark } from "./marks";\n\n'
        + "export const APP_MARKS: Record<string, Mark> = {\n"
        + "".join(entries)
        + "};\n"
    )


# --- catalogue ---------------------------------------------------------------------


@dataclass
class Built:
    """One catalogue entry the script produced."""

    vendor: Vendor
    url: str
    auth: AuthKind

    def as_entry(self) -> dict[str, Any]:
        entry: dict[str, Any] = {
            "name": self.vendor.name,
            "title": self.vendor.title,
            "purpose": self.vendor.purpose,
            "url": self.url,
            "auth": self.auth,
            "category": self.vendor.category,
            "docs_url": self.vendor.docs_url,
            "keywords": list(self.vendor.keywords),
        }
        if self.vendor.oauth is not None:
            entry["oauth"] = self.vendor.oauth.model_dump(exclude_none=True)
        if self.vendor.token_help_url:
            entry["token_help_url"] = self.vendor.token_help_url
        return entry


class _IndentedDumper(yaml.SafeDumper):
    """Indents list items under their key."""

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)


def render_catalog(built: list[Built]) -> str:
    body = yaml.dump(
        {"version": 1, "entries": [b.as_entry() for b in built]},
        Dumper=_IndentedDumper,
        sort_keys=False,
        default_flow_style=None,
        allow_unicode=True,
        width=1000,
    )
    return CATALOG_HEADER + body


def existing_entries(path: Path = CATALOG_PATH) -> dict[str, dict[str, Any]]:
    if not path.exists():
        return {}
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {str(e["name"]): e for e in raw.get("entries", [])}


# --- report ------------------------------------------------------------------------


@dataclass
class Report:
    added: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    left_out: list[tuple[str, str]] = field(default_factory=list)
    letters: list[str] = field(default_factory=list)
    missing_hand: list[str] = field(default_factory=list)

    def render(self) -> str:
        if not (
            self.added
            or self.changed
            or self.left_out
            or self.letters
            or self.missing_hand
        ):
            return "No changes."
        lines: list[str] = []
        lines += [f"Added: {name}" for name in self.added]
        lines += [f"Changed: {text}" for text in self.changed]
        lines += [f"Left out: {name} ({reason})" for name, reason in self.left_out]
        lines += [f"Logo replaced by a letter: {name}" for name in self.letters]
        lines += [
            f"No hand-drawn mark in marks.ts: {name}" for name in self.missing_hand
        ]
        return "\n".join(lines)


def _compare(report: Report, built: Built, old: dict[str, Any] | None) -> None:
    if old is None:
        report.added.append(built.vendor.name)
        return
    entry = built.as_entry()
    for key in ("url", "auth"):
        if old.get(key) != entry[key]:
            report.changed.append(f"{built.vendor.name} ({key} → {entry[key]})")


# --- main --------------------------------------------------------------------------


@dataclass
class Options:
    refresh: bool = False
    dry_run: bool = False
    offline: bool = False
    only: str | None = None


async def build(
    options: Options,
    http: httpx2.AsyncClient,
    *,
    allowlist: Path = ALLOWLIST,
    catalog_path: Path = CATALOG_PATH,
    marks_path: Path = APP_MARKS_PATH,
    hand_marks: Path = MARKS_PATH,
    cache_dir: Path = CACHE_DIR,
) -> tuple[int, Report]:
    """Run the whole import and return `(exit_code, report)`."""
    vendors = load_allowlist(allowlist)
    old = existing_entries(catalog_path)
    report = Report()

    servers: list[dict[str, Any]] = []
    from_cache = False
    if any(v.source == "registry" for v in vendors):
        cache = cache_dir / "registry.json"
        from_cache = cache.exists() and (options.offline or not options.refresh)
        if options.offline and not cache.exists():
            raise RegistryUnavailable(
                "--offline needs a cached registry; run once with --refresh"
            )
        servers = await fetch_registry(
            http, cache=cache, refresh=options.refresh and not options.offline
        )

    built: list[Built] = []
    for vendor in vendors:
        if options.only is not None and vendor.name != options.only:
            # Other apps stay as the catalogue has them; new ones are skipped.
            if vendor.name in old:
                kept = old[vendor.name]
                built.append(Built(vendor, str(kept["url"]), kept["auth"]))
            continue
        result = await _build_one(
            vendor, servers, http, offline=options.offline, old=old.get(vendor.name)
        )
        if isinstance(result, Rejection):
            reason = result.reason
            if reason == NO_REGISTRY_ENTRY and from_cache:
                reason += "; the cached registry may be old, run with --refresh"
            report.left_out.append((vendor.name, reason))
            continue
        _compare(report, result, old.get(vendor.name))
        built.append(result)

    marks: dict[str, MarkData] = {}
    if not options.offline:
        hand = hand_kept_marks(hand_marks)
        colors = (
            await _simple_icons_colors(http)
            if any(v.logo.startswith("simple-icons:") for v in vendors)
            else {}
        )
        for b in built:
            if b.vendor.name in hand or b.vendor.logo == "letter":
                continue
            if b.vendor.logo == "hand":
                report.missing_hand.append(b.vendor.name)
                continue
            mark = await fetch_mark(b.vendor, http, colors)
            if mark is None:
                report.letters.append(b.vendor.name)
            else:
                marks[b.vendor.name] = mark

    if not options.dry_run:
        _write_if_changed(catalog_path, render_catalog(built))
        if not options.offline:
            _write_if_changed(marks_path, render_app_marks(marks))
    return (1 if report.left_out else 0), report


async def _build_one(
    vendor: Vendor,
    servers: list[dict[str, Any]],
    http: httpx2.AsyncClient,
    *,
    offline: bool,
    old: dict[str, Any] | None,
) -> Built | Rejection:
    if vendor.source == "registry":
        selected = select_remote(servers, vendor)
        if isinstance(selected, Rejection):
            return selected
        url = selected
    else:
        url = vendor.url or ""
    try:
        check_url(url)
    except ConnectorConfigError as exc:
        return Rejection(str(exc))
    if offline:
        auth = vendor.expect_auth or (old or {}).get("auth")
        if auth is None:
            return Rejection("--offline can't check sign-in for a new app")
        return Built(vendor, url, auth)
    auth_or_reason = await classify_auth(vendor, url, http)
    if isinstance(auth_or_reason, Rejection):
        return auth_or_reason
    return Built(vendor, url, auth_or_reason)


async def _simple_icons_colors(http: httpx2.AsyncClient) -> dict[str, str]:
    response = await http.get(
        f"{SIMPLE_ICONS}/data/simple-icons.json", timeout=REQUEST_TIMEOUT_S
    )
    response.raise_for_status()
    data = response.json()
    icons = data if isinstance(data, list) else data.get("icons", [])
    return simple_icons_colors(icons)


def _write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(text, encoding="utf-8")
    temp.replace(path)


def parse_args(argv: list[str]) -> Options:
    parser = argparse.ArgumentParser(
        description=__doc__.splitlines()[0] if __doc__ else None
    )
    parser.add_argument(
        "--refresh", action="store_true", help="download the registry again"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="print the report without writing files"
    )
    parser.add_argument(
        "--offline",
        action="store_true",
        help="use the cache; keep known sign-in methods and logos",
    )
    parser.add_argument(
        "--only", metavar="NAME", help="check one app; keep the others as they are"
    )
    args = parser.parse_args(argv)
    return Options(
        refresh=args.refresh, dry_run=args.dry_run, offline=args.offline, only=args.only
    )


async def _main(argv: list[str]) -> int:
    options = parse_args(argv)
    async with httpx2.AsyncClient(follow_redirects=True) as http:
        try:
            code, report = await build(options, http)
        except RegistryUnavailable as exc:
            print(f"Couldn't reach the MCP Registry: {exc}", file=sys.stderr)
            return 2
    print(report.render())
    return code


if __name__ == "__main__":
    sys.exit(asyncio.run(_main(sys.argv[1:])))
